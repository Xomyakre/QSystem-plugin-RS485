        port.setStopBits(Integer.parseInt((String) comboBoxStopBits.getSelectedItem()));

        /*
         $E0, $00, SysNum, COM0, COM1, COM2, CRCH, CRCL – заголовок пакета.
         DATA0, DATA1, DATA2...DATAN, DATA_CRC – передаваемые данные.
         $E0 – стартовый байт
         $00 – адрес отправителя. (Компьютер всегда $00)
         SysNum – адрес получателя [1...254].
         Примечание. Если SysNum = 255, данные принимают все Табло, но не отвечают!
         COM0...2 – 3 байта команды.
         CRCH, CRCL – контрольные числа 6 байт заголовка пакета. Вычисляются по формулам:
         CRC = SUM (всех байт, начиная с $E0);
         CRCL = LOW (CRC);
         CRCH = HIGH (CRC) + LOW (CRC);
         DATA0...DATAN – набор от 1 до N+1 байт данных, максимальное число N определяется командой.
         DATA_CRC – контрольная сумма данных вычисляется по формуле
         DATA_CRC = SUM (DATA0...DATAN).
         Описание команд.
         1) $00,NN,MM – Загрузка (NN*256)+MM байт в видеобуфер устройства. Данные без сжатия (Алгоритм 0).
         Здесь: NN = 0...3, MM = 0...256.
         $E0, $00, SysNum, $00, NN, MM, CRCH, CRCL, DATA0...DATAN, DATA_CRC.
         Здесь N = 0...1023.
         */
        byte[] mess = new byte[12];
        mess[0] = -32;// $E0 – стартовый байт = 224 = -32
