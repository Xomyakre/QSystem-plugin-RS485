    private void btnDocashChangeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDocashChangeActionPerformed
        /*
         Чтобы сменить сетевые параметры табло, надо отправить команду (или её часть): http://192.168.1.60/?command=setnet&IP=192.168.2.142&MASK=255.255.255.0&port=80&GW=192.168.2.1&DNS=192.168.2.1&MAC=18-14-C0-A8-02-8E, где:
         IP=192.168.2.142 - новый IP;
         MASK=255.255.255.0 - новая маска подсети;
         port=80 - новый порт, через который будет работать табло;
         GW=192.168.2.1 - новый шлюз (ненужный для табло параметр);
         DNS=192.168.2.1 - адрес DNS (ненужный для табло параметр);
         MAC=18-14-C0-A8-02-8E - новый МАС-адрес (ненужный для табло параметр);

         Т.е. можно отправить только http://192.168.1.60/?command=setnet&IP=192.168.2.142 и будет изменён только IP, а остальные параметры останутся прежними.
         */
        String url;
        final String charset = "UTF-8";  // Or in Java 7 and later, use the constant: java.nio.charset.StandardCharsets.UTF_8.name()
        try {
            url = String.format("http://%s:%s/?command=setnet",
                    URLEncoder.encode(tfDocashAddress.getText(), charset),
                    URLEncoder.encode(spDocashPort.getValue().toString(), charset));

        } catch (UnsupportedEncodingException ex) {
            throw new RuntimeException(ex);
        }
        if (!tfDocashIP.getText().isEmpty()) {
            url = url + "&IP=" + tfDocashIP.getText();
        }
        if (!tfDocashMask.getText().isEmpty()) {
            url = url + "&MASK=" + tfDocashMask.getText();
        }
        if (spDocashPortChange.getValue() != null) {
            url = url + "&port=" + spDocashPortChange.getValue();
        }
        if (!tfDocashGW.getText().isEmpty()) {
            url = url + "&GW=" + tfDocashGW.getText();
        }
        if (!tfDocashDns.getText().isEmpty()) {
            url = url + "&DNS=" + tfDocashDns.getText();
        }
        if (!tfDocashMac.getText().isEmpty()) {
            url = url + "&MAC=" + tfDocashMac.getText();
        }

        taDocash.setText("-->>\n");
        taDocash.append(url + "\n");
        try {
            final String res = sendGet(url);
            if (res == null) {
                taDocash.append("Ошибка получения ответа по запросу\n");
            }
            taDocash.append("<<--\n");
            taDocash.append(res);
        } catch (Exception ex) {
            taDocash.append("Ошибка запроса\n");
            System.err.println(ex);
        }
    }//GEN-LAST:event_btnDocashChangeActionPerformed

    private String sendGet(String url) throws IOException {
        if (1 == 2) {
            return "";
        }
        final URL obj = new URL(url);
        final HttpURLConnection con = (HttpURLConnection) obj.openConnection();
        // optional default is GET
        con.setRequestMethod("GET");
        //add request header
        //con.setRequestProperty("User-Agent", USER_AGENT);
        int responseCode = con.getResponseCode();
        if (responseCode != 200) {
            System.err.println("Bad responce code=" + responseCode);
            taDocash.append("Bad responce code=" + responseCode + "\n");
            return null;
        }
        final StringBuilder response = new StringBuilder();
        try (BufferedReader in = new BufferedReader(new InputStreamReader(con.getInputStream()))) {
            String inputLine;
            while ((inputLine = in.readLine()) != null) {
                response.append(inputLine);
            }
        }
        //print result
        final String res = response.toString();
        response.setLength(0);
        return res;
    }

    static byte toByte(int i) {
        i = i % 256;
        return (byte) (i >= 0 && i < 128 ? i : (i - 256));
    }

    static int toInt(byte b) {
        return (int) b & 0x000000FF;
    }

    public static boolean[] toBooleanArray(byte[] bytes) {
        final BitSet bits = BitSet.valueOf(bytes);
        final boolean[] bools = new boolean[bytes.length * 8];
        for (int i = bits.nextSetBit(0); i != -1; i = bits.nextSetBit(i + 1)) {
            bools[i] = true;
        }
        return bools;
    }

    public static byte[] toByteArraySI(boolean[] bools) {
        BitSet bits = new BitSet(bools.length);
        for (int i = 0; i < bools.length; i++) {
            if (bools[i]) {
                bits.set(i);
            }
        }
        return bits.toByteArray();
    }

    public static byte[] toByteArrayBI(boolean[] input) {
        byte[] toReturn = new byte[input.length / 8];
        for (int entry = 0; entry < toReturn.length; entry++) {
            for (int bit = 0; bit < 8; bit++) {
                if (input[entry * 8 + bit]) {
                    toReturn[entry] |= (128 >> bit);
                }
            }
        }
        return toReturn;
    }

